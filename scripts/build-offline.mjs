// Builds:
//   1. src/ui/samples.js       – the synthetic sample notes, embedded for the "Load sample" menu
//   2. dist/hipa-offline.html  – the whole app in ONE file that works with no internet at all
//
// Usage: node scripts/build-offline.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');
const SITE = 'https://arqamsalam.github.io/HIPA/';

// 1. samples.js
const samples = { ed: read('samples/ed-note.txt'), dc: read('samples/discharge-summary.txt'), nh: read('samples/nursing-home.txt') };
writeFileSync(join(root, 'src/ui/samples.js'),
  '/* Generated by scripts/build-offline.mjs from samples/*.txt — synthetic data only. */\n' +
  'window.HIPA_SAMPLES = ' + JSON.stringify(samples, null, 2) + ';\n');

// 2. single-file offline build
let html = read('index.html');
const sha = (s) => `'sha256-${createHash('sha256').update(s).digest('base64')}'`;
const scriptHashes = [];
const styleHashes = [];

html = html.replace(/<script src="([^"]+)"><\/script>/g, (_, src) => {
  const code = read(src).replace(/<\/script/gi, '<\\/script');
  scriptHashes.push(sha(code));
  return `<script>${code}</script>`;
});
html = html.replace(/<link rel="stylesheet" href="([^"]+)">/g, (_, href) => {
  const css = read(href);
  styleHashes.push(sha(css));
  return `<style>${css}</style>`;
});
const icon = 'data:image/svg+xml;base64,' + Buffer.from(read('assets/favicon.svg')).toString('base64');
html = html.replaceAll('assets/favicon.svg', icon);
html = html.replace('href="guide.html', `href="${SITE}guide.html`);
html = html.replaceAll('href="guide.html', `href="${SITE}guide.html`);
html = html.replace(/<a href="hipa-offline\.html" download>Download offline version<\/a>/, '<span>Offline edition</span>');
html = html.replace(
  /content="default-src 'none'; script-src 'self'; style-src 'self';/,
  `content="default-src 'none'; script-src ${scriptHashes.join(' ')}; style-src ${styleHashes.join(' ')};`
);

mkdirSync(join(root, 'dist'), { recursive: true });
writeFileSync(join(root, 'dist/hipa-offline.html'), html);
console.log(`samples.js written; dist/hipa-offline.html ${(html.length / 1024).toFixed(0)} KB`);
